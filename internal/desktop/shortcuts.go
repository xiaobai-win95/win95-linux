const (
	shortcutsDir      = "/root/桌面"
	launchRequestPath = "/run/win95-launch"
	shortcutMarker    = "X-Win95-Shortcut"
	shortcutPkgKey    = "X-Win95-Package"
)

type shortcutEntry struct {
	Name       string
	NameZh     string
	Comment    string
	Exec       string
	Icon       string
	Categories string
	Terminal   bool
	NoDisplay  bool
	Hidden     bool
	Win95Hide  bool
	Package    string
	Path       string
}

// parseShortcut reads the [Desktop Entry] group. Entries that are hidden from
// application menus are ignored, but the raw file is still used when removing
// shortcuts generated by the package manager.
func parseShortcut(path string) (shortcutEntry, bool) {
	b, err := os.ReadFile(path)
	if err != nil {
		return shortcutEntry{}, false
	}
	e := shortcutEntry{Path: path}
	section := false
	seen := false
	appType := ""
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "[") {
			section = line == "[Desktop Entry]"
			if section {
				seen = true
			}
			continue
		}
		if !section {
			continue
		}
		key, val, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		key, val = strings.TrimSpace(key), strings.TrimSpace(val)
		switch key {
		case "Type":
			appType = val
		case "Name":
			e.Name = val
		case "Name[zh_CN]":
			e.NameZh = val
		case "Name[zh_TW]":
			if e.NameZh == "" {
				e.NameZh = val
			}
		case "Comment":
			e.Comment = val
		case "Exec":
			e.Exec = val
		case "Icon":
			e.Icon = val
		case "Categories":
			e.Categories = val
		case "Terminal":
			e.Terminal = val == "true"
		case "NoDisplay":
			e.NoDisplay = val == "true"
		case "Hidden":
			e.Hidden = val == "true"
		case "X-Win95-Hide":
			e.Win95Hide = val == "true"
		case shortcutPkgKey:
			e.Package = val
		}
	}
	if !seen || e.Name == "" || e.Exec == "" {
		return e, false
	}
	if appType != "" && appType != "Application" {
		return e, false
	}
	if e.NoDisplay || e.Hidden {
		return e, false
	}
	return e, true
}

func cleanExec(s string) string {
	var out []string
	for _, f := range strings.Fields(s) {
		if len(f) == 2 && f[0] == '%' {
			continue
		}
		if len(f) > 1 && strings.Contains(f, "%") {
			f = strings.TrimSuffix(f, "%f")
			f = strings.TrimSuffix(f, "%F")
			f = strings.TrimSuffix(f, "%u")
			f = strings.TrimSuffix(f, "%U")
		}
		if f != "" {
			out = append(out, f)
		}
	}
	return strings.Join(out, " ")
}

func shortcutIcon(e shortcutEntry) ui.IconKind {
	text := strings.ToLower(e.Exec + " " + e.Categories + " " + e.Name)
	switch {
	case strings.Contains(text, "terminal"), strings.Contains(text, "shell"):
		return ui.IcoTerminal
	case strings.Contains(text, "browser"), strings.Contains(text, "firefox"),
		strings.Contains(text, "chrom"), strings.Contains(text, "webkit"):
		return ui.IcoBrowser
	case strings.Contains(text, "paint"), strings.Contains(text, "graphics"),
		strings.Contains(text, "image"):
		return ui.IcoPaint
	case strings.Contains(text, "calc"):
		return ui.IcoCalc
	case strings.Contains(text, "package"), strings.Contains(text, "software"):
		return ui.IcoPackage
	}
	return ui.IcoSetup
}

func sanitizeShortcutName(name string) string {
	var b strings.Builder
	for _, r := range name {
		switch r {
		case '/', '\\', ':', '*', '?', '"', '<', '>', '|', '\n', '\r':
			b.WriteRune('_')
		default:
			b.WriteRune(r)
		}
	}
	out := strings.TrimSpace(b.String())
	if out == "" {
		out = "快捷方式"
	}
	if len([]rune(out)) > 48 {
		out = string([]rune(out)[:48])
	}
	return out
}

func oneLine(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\n", " "), "\r", " ")
}

// generateDesktopShortcuts creates launchers for the GUI programs shipped by
// pkg. It returns the paths of the files it wrote.
func generateDesktopShortcuts(pkg string) ([]string, error) {
	if pkg == "" {
		return nil, nil
	}
	out, err := exec.Command(apkBin, "info", "-L", pkg).Output()
	if err != nil {
		return nil, fmt.Errorf("apk info -L %s: %w", pkg, err)
	}
	var entries []shortcutEntry
	seen := map[string]bool{}
	for _, line := range strings.Split(string(out), "\n") {
		path := strings.TrimSpace(line)
		if !strings.HasPrefix(path, "/usr/share/applications/") || !strings.HasSuffix(path, ".desktop") {
			continue
		}
		e, ok := parseShortcut(path)
		if !ok || seen[e.Exec] {
			continue
		}
		seen[e.Exec] = true
		entries = append(entries, e)
	}
	if len(entries) == 0 {
		candidates := []string{pkg}
		if strings.HasPrefix(pkg, "xfce4-") {
			candidates = append(candidates, strings.TrimPrefix(pkg, "xfce4-"))
		}
		for _, cmd := range candidates {
			if path, err := exec.LookPath(cmd); err == nil {
				entries = append(entries, shortcutEntry{Name: pkg, Exec: path, Terminal: true})
				break
			}
		}
	}
	if err := os.MkdirAll(shortcutsDir, 0o755); err != nil {
		return nil, err
	}
	var created []string
	for _, e := range entries {
		name := e.NameZh
		if name == "" {
			name = e.Name
		}
		base := sanitizeShortcutName(name)
		target := filepath.Join(shortcutsDir, base+".desktop")
		if b, err := os.ReadFile(target); err == nil && !strings.Contains(string(b), shortcutMarker+"=true") {
			target = filepath.Join(shortcutsDir, base+" ("+pkg+").desktop")
		}
		icon := e.Icon
		if icon == "" {
			icon = "application-x-executable"
		}
		var b strings.Builder
		fmt.Fprintf(&b, "[Desktop Entry]\nVersion=1.0\nType=Application\n")
		fmt.Fprintf(&b, "Name=%s\n", oneLine(e.Name))
		if e.NameZh != "" {
			fmt.Fprintf(&b, "Name[zh_CN]=%s\n", oneLine(e.NameZh))
		}
		if e.Comment != "" {
			fmt.Fprintf(&b, "Comment=%s\n", oneLine(e.Comment))
		}
		fmt.Fprintf(&b, "Exec=%s\n", oneLine(e.Exec))
		fmt.Fprintf(&b, "Icon=%s\n", oneLine(icon))
		if e.Categories != "" {
			fmt.Fprintf(&b, "Categories=%s\n", oneLine(e.Categories))
		}
		fmt.Fprintf(&b, "Terminal=%v\n", e.Terminal)
		fmt.Fprintf(&b, "StartupNotify=false\n")
		fmt.Fprintf(&b, "%s=true\n", shortcutMarker)
		fmt.Fprintf(&b, "%s=%s\n", shortcutPkgKey, pkg)
		if err := os.WriteFile(target, []byte(b.String()), 0o755); err != nil {
			continue
		}
		created = append(created, target)
	}
	return created, nil
}

func removeDesktopShortcuts(pkg string) []string {
	if pkg == "" {
		return nil
	}
	ents, err := os.ReadDir(shortcutsDir)
	if err != nil {
		return nil
	}
	var removed []string
	for _, de := range ents {
		if de.IsDir() || !strings.HasSuffix(de.Name(), ".desktop") {
			continue
		}
		path := filepath.Join(shortcutsDir, de.Name())
		b, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		ours := false
		for _, line := range strings.Split(string(b), "\n") {
			if strings.TrimSpace(line) == shortcutPkgKey+"="+pkg {
				ours = true
				break
			}
		}
		if ours {
			if os.Remove(path) == nil {
				removed = append(removed, path)
			}
		}
	}
	return removed
}

func desktopFileIcon(name string) ui.IconKind {
	switch strings.ToLower(filepath.Ext(name)) {
	case ".txt", ".md", ".log", ".conf", ".ini", ".cfg":
		return ui.IcoText
	case ".html", ".htm":
		return ui.IcoBrowser
	case ".sh":
		return ui.IcoTerminal
	}
	return ui.IcoFile
}

// refreshShortcuts rescans ~/桌面 and rebuilds the icon list. The directory
// timestamp check keeps this cheap when called from the one-second tick.
func (d *Desktop) refreshShortcuts(force bool) {
	if d.Mode != ModeDesktop {
		return
	}
	now := time.Now()
	if !force && now.Before(d.shortcutNext) {
		return
	}
	d.shortcutNext = now.Add(3 * time.Second)
	// A refresh would invalidate the indexes captured by an open popup menu
	// and interrupt a drag, so defer it until the user is done.
	if !force && (d.ctx != nil || d.dragIcon >= 0) {
		return
	}

	var mod time.Time
	if st, err := os.Stat(shortcutsDir); err == nil {
		mod = st.ModTime()
	}
	if !force && !mod.IsZero() && mod.Equal(d.shortcutMod) {
		return
	}
	d.shortcutMod = mod

	selKey := ""
	if d.selected >= 0 && d.selected < len(d.icons) {
		selKey = d.icons[d.selected].key
	}

	icons := append([]*desktopIcon{}, d.baseIcons...)
	ents, err := os.ReadDir(shortcutsDir)
	if err != nil {
		d.icons = icons
		d.selected = -1
		d.dragIcon = -1
		d.Invalidate()
		return
	}
	for _, de := range ents {
		name := de.Name()
		if strings.HasPrefix(name, ".") {
			continue
		}
		path := filepath.Join(shortcutsDir, name)
		label := name
		kind := desktopFileIcon(name)
		if !de.IsDir() && strings.HasSuffix(strings.ToLower(name), ".desktop") {
			e, ok := parseShortcut(path)
			if ok && e.Win95Hide {
				continue
			}
			if ok {
				if e.NameZh != "" {
					label = e.NameZh
				} else {
					label = e.Name
				}
				if cleanExec(e.Exec) != "" {
					kind = shortcutIcon(e)
				}
			}
		}
		p := path
		icons = append(icons, &desktopIcon{
			label: label,
			kind:  kind,
			key:   p,
			path:  p,
			isDir: de.IsDir(),
			action: func() {
				d.openDesktopPath(p)
			},
		})
	}
	// Folders before files, then by display name; base icons stay in place.
	nBase := len(d.baseIcons)
	if len(icons) > nBase {
		dyn := icons[nBase:]
		sort.SliceStable(dyn, func(i, j int) bool {
			if dyn[i].isDir != dyn[j].isDir {
				return dyn[i].isDir
			}
			return strings.ToLower(dyn[i].label) < strings.ToLower(dyn[j].label)
		})
	}
	d.icons = icons
	if len(d.iconPositions) > 0 {
		keep := map[string]iconPoint{}
		for _, ic := range d.icons {
			if p, ok := d.iconPositions[ic.key]; ok {
				keep[ic.key] = p
			}
		}
		d.iconPositions = keep
	}
	d.selected = -1
	if selKey != "" {
		for i, ic := range d.icons {
			if ic.key == selKey {
				d.selected = i
				break
			}
		}
	}
	if d.dragIcon >= len(d.icons) {
		d.dragIcon = -1
	}
	d.Invalidate()
}

func (d *Desktop) RefreshShortcuts() { d.refreshShortcuts(true) }
